    #[mononoke::test]
    fn test_registered_messages_are_valid() {
        let mut implementations = HashSet::new();
        for registration in registrations() {
            let implementation = registration.implementation;
            assert!(
                implementations.insert(implementation),
                "{implementation} is registered twice"
            );
            let mut names = HashSet::new();
            for spec in registration.specs {
                assert!(
                    names.insert(spec.name),
                    "{implementation} declares {} twice",
                    spec.name
                );
                assert!(
                    !spec.description.trim().is_empty(),
                    "{implementation}.{} has no description",
                    spec.name
                );
                let mut params = HashSet::new();
                for param in spec.params {
                    assert!(
                        param.name != DEFAULT_PLACEHOLDER && params.insert(param.name),
                        "{implementation}.{} has an invalid or repeated parameter {}",
                        spec.name,
                        param.name
                    );
                    assert!(
                        !param.description.trim().is_empty(),
                        "{implementation}.{}.{} has no description",
                        spec.name,
                        param.name
                    );
                }
            }
            for (name, _) in registration.defaults {
                assert!(
                    names.contains(name),
                    "{implementation} replaces the default of undeclared message {name}"
                );
            }
            for message in registration.describe().messages {
                let spec = registration
                    .specs
                    .iter()
                    .find(|spec| spec.name == message.name)
                    .expect("described messages are declared");
                // A default can only rely on the whole match, which every
                // regex has.
                let groups = spec.captures.then(CaptureGroups::whole_match);
                assert!(
                    Template::parse(message.default, spec.params, false, groups.as_ref()).is_ok(),
                    "{implementation}.{} has an invalid default",
                    message.name
                );
            }
        }
    }

