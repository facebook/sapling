class AdvisoryTest(unittest.TestCase):
    def _summary(
        self,
        results: Mapping[str, str],
        executions: Mapping[str, dict[str, str] | None],
    ) -> tuple[int, dict[str, Any]]:
        """Run the real CLI over paired execution and verdict artifacts."""
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            for name, kind in results.items():
                directory = root / name
                directory.mkdir()
                (directory / "verdict.json").write_bytes(
                    encode_verdict(_VERDICTS[kind])
                )
            for name, execution in executions.items():
                directory = root / name
                directory.mkdir(exist_ok=True)
                if execution is not None:
                    (directory / "execution.json").write_text(json.dumps(execution))
            with redirect_stdout(StringIO()) as out:
                code = _main(
                    [
                        "release-summary",
                        "--target",
                        "edenfs",
                        "--decks",
                        str(DECKS),
                        "--artifacts",
                        str(root),
                    ]
                )
        return code, json.loads(out.getvalue())

    def _all(self) -> dict[str, str]:
        specs = _specs()
        results = {name: spec.metadata["expected"] for name, spec in specs.items()}
        results["calibration-320001"] = REJECT
        del results["bug-113"]
        return results

    def _executions(self, results: Mapping[str, str]) -> dict[str, Any]:
        executions: dict[str, Any] = {
            name: {"status": COMPLETED, "reason": "ok"} for name in results
        }
        executions["bug-113"] = {
            "status": CONTAINMENT_TIMEOUT,
            "reason": "runner exceeded 240s",
            "cleanup": MOUNT_WEDGED_PREFIX + "aborted connection 52",
        }
        return executions

    def test_release_lanes_and_reproduced_reject_decks(self) -> None:
        results = self._all()
        code, summary = self._summary(results, self._executions(results))
        self.assertEqual((0, "PASS"), (code, summary["gate"]))
        self.assertEqual("reject", summary["reject_decks"]["bug-788"])
        self.assertNotIn("bug-788", summary["accept_decks"])
        self.assertEqual(
            {
                f"fd-across-type-change-{arm}"
                for arm in ("materialized", "unloaded", "unmaterialized")
            },
            set(summary["not_evaluated_decks"]),
        )
        self.assertEqual(["bug-113", "bug-775", "bug-788"], summary["reproduced"])
        self.assertEqual({"pin": "reject", "master": "accept"}, summary["calibration"])
        for name in DIFFERENTIAL_DECKS:
            self.assertEqual("accept", summary["accept_decks"][name])

    def test_blocking_mismatches_and_incomplete_runs_fail_the_gate(self) -> None:
        for name, kind in (
            ("red-control", REJECT),
            ("fd-across-type-change-unloaded", ACCEPT),
            ("calibration-320001", ACCEPT),
        ):
            with self.subTest(name=name):
                results = {**self._all(), name: kind}
                code, summary = self._summary(results, self._executions(results))
                self.assertEqual((1, [name]), (code, summary["failures"]))
        results = self._all()
        executions = self._executions(results)
        executions["cancel-status"] = {"status": "harness-failure", "reason": "x"}
        executions["bug-788"] = {"status": "harness-failure", "reason": "x"}
        code, summary = self._summary(results, executions)
        self.assertEqual((1, ["cancel-status"]), (code, summary["unmeasured"]))
        self.assertNotIn("bug-788", summary["reproduced"])
        del results["calibration"]
        code, summary = self._summary(results, self._executions(results))
        self.assertEqual((1, ["calibration"]), (code, summary["missing"]))

    def test_a_malformed_verdict_exits_2(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            run = Path(temporary) / "calibration"
            run.mkdir()
            (run / "execution.json").write_text("{bad")
            with redirect_stdout(StringIO()):
                code = _main(
                    [
                        "release-summary",
                        "--target",
                        "edenfs",
                        "--decks",
                        str(DECKS),
                        "--artifacts",
                        temporary,
                    ]
                )
        self.assertEqual(2, code)

    def test_advisory_runner_skips_without_opt_in(self) -> None:
        run = mock.Mock()
        with tempfile.TemporaryDirectory() as temporary:
            result = advisory.run_advisory(
                Path(temporary), Path("absent"), specs=_specs(), run=run
            )
        self.assertEqual("skipped", result)
        run.assert_not_called()

    def test_preflight_outcomes(self) -> None:
        """Only a typed calibration-rule finding on the known SUT permits replays."""
        specs = _specs()
        cases = (
            (
                True,
                synthetic_verdict(
                    _violated("status.sl-fuse-stale-status", Attribution.PRODUCT)
                ),
                "calibrated",
            ),
            (
                True,
                synthetic_verdict(
                    _violated("bytes.stale-read", Attribution.UNDETERMINED)
                ),
                "calibrated",
            ),
            (True, synthetic_verdict(satisfied_bytes()), "detection-power-regression"),
            (False, synthetic_verdict(satisfied_bytes()), "vintage-unverified"),
            (
                True,
                synthetic_verdict(
                    _violated("status.status-diff-mismatch", Attribution.PRODUCT)
                ),
                None,
            ),
            (
                True,
                synthetic_verdict(
                    _violated("bytes.stale-read", Attribution.ORACLE_SUSPECT)
                ),
                None,
            ),
        )
        for known, verdict, expected in cases:
            with self.subTest(known=known, reason=verdict.reason):
                result = ExplorationResult(
                    Execution("completed", "", 0, 0), verdict, ""
                )
                run = mock.Mock(return_value=result)
                with tempfile.TemporaryDirectory() as temporary:
                    artifacts = Path(temporary)
                    binary = artifacts / "edenfs"
                    binary.write_bytes(b"known" if known else b"unknown")
                    with (
                        mock.patch.object(
                            advisory,
                            "PINNED_SHA256",
                            hashlib.sha256(b"known").hexdigest(),
                        ),
                        mock.patch.dict(os.environ, {"EDENFS_SERVER_PATH": "current"}),
                    ):
                        call = functools.partial(
                            advisory.run_advisory,
                            artifacts,
                            binary,
                            specs=specs,
                            run=run,
                            opt_in=True,
                        )
                        if expected is None:
                            with self.assertRaises(RuntimeError):
                                call()
                        else:
                            self.assertEqual(expected, call())
                        self.assertEqual("current", os.environ["EDENFS_SERVER_PATH"])
                replays = len(specs) if expected == "calibrated" else 0
                self.assertEqual(int(known) + replays, run.call_count)

    def test_advisory_replays(self) -> None:
        """Record advisory outcomes only when an operator explicitly opts in."""
        if os.environ.get("EDEN_EXPLORATORY_REPLAYS") != "1":
            self.skipTest("set EDEN_EXPLORATORY_REPLAYS=1 for advisory replays")
        from eden.integration.correctness.exploratory.edenfs.target import run_live

        result = advisory.run_advisory(
            Path(os.environ["EDEN_EXPLORATORY_ARTIFACTS"]),
            Path(os.environ["EDEN_EXPLORATORY_PINNED_SUT"]),
            specs=_specs(),
            run=lambda spec, path: run_live(spec, path),
            opt_in=True,
        )
        self.assertEqual("calibrated", result, result)


class ReleaseConfigTest(unittest.TestCase):
    """The release job and the shipped policy stay report-only."""

    def setUp(self) -> None:
        path = Path(advisory.__file__).with_name("ci") / "release-decks.json"
        self.spec = json.loads(path.read_text())
        (self.step,) = self.spec["args"]["steps"]

    def test_release_job_runs_the_blocking_lanes_then_the_advisory_summary(
        self,
    ) -> None:
        shell = self.step["shell"]
        subprocess.run(["bash", "-n"], input=shell, text=True, check=True)
        live = shell.index("exploratory:decks_live_test")
        replays = shell.index("exploratory:decks_test")
        summary = shell.index("release-summary --target edenfs")
        self.assertLess(live, replays)
        self.assertLess(replays, summary)
        self.assertIn("--env EDEN_EXPLORATORY_REPLAYS=1", shell[live:replays])

    def test_release_job_files_nothing_and_only_reads_the_pinned_sut(self) -> None:
        shell = self.step["shell"]
        self.assertEqual(1, shell.count("manifold "))
        self.assertIn("manifold get ", shell)
        for needle in (
            "findings",
            "tasks.",
            "artifacts.artifact",
            "scribe",
            "--ledger",
            "meta ",
            "manifold put",
        ):
            self.assertNotIn(needle, shell)
