def _specs() -> dict[str, RunSpec]:
    return advisory.load_specs(DECKS, EDENFS_TARGET)


def _identity(verdict: Verdict) -> tuple[str, list[str], list[str]]:
    """Return a verdict's kind, sorted rules, and sorted canonical keys."""
    run = keyed(verdict, EDENFS_TARGET)
    assert not run.incomplete, run.incomplete
    rules = sorted({rule for o in run.occurrences for rule in o.rules})
    return verdict.kind, rules, sorted(o.task_key for o in run.occurrences)


def _reproducer_keys(task: str) -> dict[str, list[str]]:
    """Return each canonical key a task's translated reproducer yields, with its rules."""
    (reproducer,) = (r for r in known_reproducers.reproducers() if r.task == task)
    verdict = check(
        EDENFS_TARGET,
        reproducer.spec,
        reproducer.events,
        execution=known_reproducers.COMPLETED,
    )
    return {
        o.task_key: list(o.rules) for o in keyed(verdict, EDENFS_TARGET).occurrences
    }


def _violated(rule: str, attribution: Attribution) -> PropertyResult:
    return PropertyResult(
        rule.split(".")[0],
        (
            ObligationResult(
                rule_id=rule,
                scope="r",
                subject=path_subject(R0),
                status=ObligationStatus.VIOLATED,
                attribution=attribution,
                reason=f"{rule} violated",
            ),
        ),
    )


class DeckValidationTest(unittest.TestCase):
    def _validate(self, metadata: Mapping[str, Any]) -> None:
        expected = metadata["expected"]
        self.assertIn(expected, {ACCEPT, REJECT, NOT_EVALUATED})
        self.assertIs(False, metadata["fatal_eden_bug"])
        if expected == REJECT:
            self.assertRegex(metadata["task"], r"^T\d+$")
            self.assertTrue(
                metadata.get("expected_task_key") or metadata.get("expected_execution")
            )
        else:
            self.assertNotIn("expected_rules", metadata)
        self.assertEqual(
            expected == NOT_EVALUATED,
            bool(metadata.get("expected_not_evaluated")),
        )
        if WAITING_ON in metadata:
            self.assertRegex(metadata[WAITING_ON], r"^T\d+$")

    def test_every_deck_validates_and_names_its_lane(self) -> None:
        specs = _specs()
        self.assertEqual(FROZEN_DECKS | DIFFERENTIAL_DECKS, set(specs))
        self.assertEqual(320001, specs["calibration"].seed)
        for name, spec in specs.items():
            with self.subTest(deck=name):
                self._validate(spec.metadata)

    def test_a_deck_may_wait_on_a_task(self) -> None:
        metadata = _specs()["red-control"].metadata
        self._validate({**metadata, WAITING_ON: "T1"})
        with self.assertRaisesRegex(AssertionError, "soon"):
            self._validate({**metadata, WAITING_ON: "soon"})

    def test_recorded_histories_judge_to_their_decks_expected_verdict(self) -> None:
        """Every not-evaluated deck has a recorded live history, and each recorded
        history gives its deck's `expected` verdict and exactly its
        `expected_not_evaluated` reasons, so drift fails without a live run."""
        specs = _specs()
        recorded = {
            path.name.removesuffix(".history.jsonl"): path
            for path in sorted(HISTORIES.glob("*.history.jsonl"))
        }
        self.assertLessEqual(
            {n for n, s in specs.items() if s.metadata["expected"] == NOT_EVALUATED},
            set(recorded),
        )
        for name, path in recorded.items():
            with self.subTest(deck=name):
                spec = specs[name]
                events = [
                    event_from_json(json.loads(line))
                    for line in path.read_text().splitlines()
                ]
                verdict = check(
                    EDENFS_TARGET, spec, events, execution={"status": "completed"}
                )
                self.assertEqual(
                    spec.metadata["expected"], verdict.kind, verdict.reason
                )
                self.assertEqual(
                    spec.metadata.get("expected_not_evaluated", []),
                    advisory.not_evaluated_reasons(verdict),
                )

    def test_calibration_observes_before_second_write(self) -> None:
        spec = _specs()["calibration"]
        self.assertEqual(
            ["w0", "w2"], [a.id for a in spec.actions if a.kind == "write"]
        )
        for earlier, later in zip(
            ("w0", "u1", "s1", "f0", "t0"), ("u1", "s1", "f0", "t0", "w2")
        ):
            self.assertIn(earlier, finish_before(spec, later))
        self.assertEqual(
            finish_before(spec, "w2"), {a.id for a in spec.actions} - {"w2"}
        )


class DeckIdentityTest(unittest.TestCase):
    maxDiff = None

    def test_reject_decks_name_a_key_their_translated_reproducer_yields(self) -> None:
        """`expected_rules` are the rules of the key `expected_task_key` names."""
        specs = _specs()
        keyed_decks = {n for n, s in specs.items() if "expected_task_key" in s.metadata}
        self.assertEqual({"bug-788"}, keyed_decks)
        for name in sorted(keyed_decks):
            with self.subTest(deck=name):
                metadata = specs[name].metadata
                keys = _reproducer_keys(metadata["task"])
                self.assertIn(metadata["expected_task_key"], keys)
                self.assertEqual(
                    keys[metadata["expected_task_key"]], metadata["expected_rules"]
                )
        self.assertEqual(
            ["execution.operation-timeout"],
            specs["bug-775"].metadata["expected_execution"],
        )
        self.assertEqual(
            ["execution.mount-wedged"],
            specs["bug-113"].metadata["expected_execution"],
        )

    def test_bug_788_deck_is_the_reproducers_runspec(self) -> None:
        spec = _specs()["bug-788"]
        (reproducer,) = (
            r for r in known_reproducers.reproducers() if r.task == "T288573788"
        )
        self.assertEqual(reproducer.spec.actions, spec.actions)
        self.assertEqual(reproducer.spec.actors, spec.actors)
        self.assertEqual(reproducer.spec.environment, spec.environment)

    def test_bug_113_deck_overlaps_by_its_task_declaration(self) -> None:
        """The T293953113 deck keeps its unlink inside the checkout by declaration."""
        spec = _specs()["bug-113"]
        self.assertEqual(WALK_DEADLOCK_TASK, spec.metadata["task"])
        validate(spec, EDENFS_TARGET)

    def test_readdir_deck_holds_only_unchanged_wide_entries(self) -> None:
        """The readdir-across-checkout control streams 2000 entries no revision replaces."""
        environment = _specs()["readdir-across-checkout"].environment.target
        wide = environment["setup_profile"]["wide_dir"]
        self.assertEqual((False, 2000), (wide["churn_all"], wide["entries"]))

    def test_red_control_deck_names_exact_control_rule_sets(self) -> None:
        expected = _specs()["red-control"].metadata["expected_controls"]
        self.assertEqual(
            {c: sorted(r) for c, r in target_control_rules(EDENFS_TARGET).items()},
            expected,
        )
        self.assertEqual(sorted(EDENFS_TARGET.red_controls), sorted(expected))

    def test_only_the_generated_differential_decks_opt_into_the_reference(self) -> None:
        """Opted decks are validator-admitted paired specs; every other deck stays plain."""
        specs = _specs()
        self.assertEqual(
            DIFFERENTIAL_DECKS, {n for n, s in specs.items() if reference_clone(s)}
        )
        for name in sorted(DIFFERENTIAL_DECKS):
            with self.subTest(deck=name):
                spec = specs[name]
                validate(spec, EDENFS_TARGET)
                validate_comparable(spec)
                self.assertEqual("accept", spec.metadata["expected"])
                self.assertFalse(
                    [a for a in spec.actions if a.kind.startswith("fault")]
                )


